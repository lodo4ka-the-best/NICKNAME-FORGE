def создать_папки():
    for папка in ПАПКИ:
        путь = КОРЕНЬ / папка
        путь.mkdir(parents=True, exist_ok=True)
        print(f"  📁 {папка}/")


def создать_файлы():
    for папка, файлы in ФАЙЛЫ.items():
        for имя in файлы:
            путь = КОРЕНЬ / папка / имя
            if путь.exists():
                print(f"  ⏭  {папка}/{имя} (уже есть)")
                continue
            содержимое = ШАБЛОНЫ.get(имя, ШАБЛОН_ПУСТОГО_PY)
            путь.write_text(содержимое, encoding="utf-8")
            print(f"  📄 {папка}/{имя}")


def создать_корневые():
    for имя in КОРНЕВЫЕ_ФАЙЛЫ:
        путь = КОРЕНЬ / имя
        if путь.exists():
            print(f"  ⏭  {имя} (уже есть)")
            continue
        содержимое = ШАБЛОНЫ.get(имя, "")
        путь.write_text(содержимое, encoding="utf-8")
        print(f"  📄 {имя}")


